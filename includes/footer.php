            const observer = new IntersectionObserver((entries) => {
                entries.forEach((entry) => {
                    if (entry.isIntersecting) {
                        entry.target.classList.add('opacity-100', 'translate-y-0');
                        entry.target.classList.remove('opacity-0', 'translate-y-6');
                        observer.unobserve(entry.target);
                    }
                });
            }, { threshold: 0.15 });

            elements.forEach((el) => observer.observe(el));
        })();
        
        // Highlight active footer links based on current page
        function highlightActiveFooterLinks() {
            // Get current page more reliably
            const pathname = window.location.pathname;
            let currentPage = pathname.split('/').pop();
            
            // Handle empty result (root path) - treat as index.php
            if (!currentPage || currentPage === '') {
                currentPage = 'index.php';
            }
            
            // Remove query parameters if any
            currentPage = currentPage.split('?')[0];
            
            // Contact links - highlight all if on contact_information.php
            if (currentPage === 'contact_information.php') {
                const serviceLinks = document.querySelectorAll('a[href="contact_information.php"]');
                serviceLinks.forEach(link => {
                    link.classList.remove('text-gray-400', 'hover:text-orange-500');
                    link.classList.add('text-[#b6ada6]', 'font-semibold');
                });
            }
            
            // Quick links - find the Quick Links section and highlight matching link
            const footerSections = document.querySelectorAll('footer .grid > div');
            footerSections.forEach(section => {
                const h4 = section.querySelector('h4');
                // Check if this is the Quick Links section
                if (h4 && h4.textContent.indexOf('Quick Links') !== -1) {
                    const links = section.querySelectorAll('a');
                    links.forEach(link => {
                        const href = link.getAttribute('href');
                        if (href === currentPage) {
                            link.classList.remove('text-gray-400', 'hover:text-orange-500');
                            link.classList.add('text-[#b6ada6]', 'font-semibold');
                        } else {
                            // Make sure non-active links are faded
                            link.classList.remove('text-orange-500', 'font-semibold', 'hover:text-orange-500');
                            link.classList.add('text-[#b6ada6]/80', 'hover:text-[#b6ada6]');
                        }
                    });
                }
            });
        }
        
        document.addEventListener('DOMContentLoaded', highlightActiveFooterLinks);
